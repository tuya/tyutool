import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

import {
  checkTauriVersionParity,
  missingNpmPackages,
  parseCargoLockVersions,
  parsePnpmImporterVersions,
  tauriCrateForNpmPackage,
} from './tauri-version-parity.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

describe('tauriCrateForNpmPackage', () => {
  it('maps the api package to the tauri crate', () => {
    expect(tauriCrateForNpmPackage('@tauri-apps/api')).toBe('tauri');
  });
  it('maps plugin packages to their crate', () => {
    expect(tauriCrateForNpmPackage('@tauri-apps/plugin-dialog')).toBe('tauri-plugin-dialog');
    expect(tauriCrateForNpmPackage('@tauri-apps/plugin-store')).toBe('tauri-plugin-store');
  });
  it('ignores non-Tauri packages', () => {
    expect(tauriCrateForNpmPackage('vue')).toBeNull();
    expect(tauriCrateForNpmPackage('@tauri-apps/cli')).toBeNull();
  });
});

describe('parsePnpmImporterVersions', () => {
  const LOCK = [
    "lockfileVersion: '9.0'",
    '',
    'importers:',
    '',
    '  .:',
    '    dependencies:',
    "      '@tauri-apps/api':",
    '        specifier: ^2',
    '        version: 2.12.4',
    "      '@tauri-apps/plugin-dialog':",
    '        specifier: ^2',
    '        version: 2.8.3',
    '      vue:',
    '        specifier: ^3.5.44',
    '        version: 3.5.44(typescript@6.0.3)',
    '',
    'packages:',
    '',
    "  '@tauri-apps/plugin-dialog@2.8.3':",
    '    resolution: {integrity: sha512-abc}',
    '',
    'snapshots:',
    '',
    "  '@tauri-apps/plugin-dialog@2.8.3':",
    '    dependencies:',
    "      '@tauri-apps/api': 9.9.9",
  ].join('\n');

  it('reads the root importer versions and strips peer suffixes', () => {
    expect(parsePnpmImporterVersions(LOCK)).toEqual({
      '@tauri-apps/api': '2.12.4',
      '@tauri-apps/plugin-dialog': '2.8.3',
      vue: '3.5.44',
    });
  });

  it('ignores the packages/snapshots sections', () => {
    // The fixture repeats `@tauri-apps/api` under snapshots at a different
    // version; the parser must keep the importer value.
    expect(parsePnpmImporterVersions(LOCK)['@tauri-apps/api']).toBe('2.12.4');
    expect(Object.keys(parsePnpmImporterVersions(LOCK))).toHaveLength(3);
  });
});

describe('parseCargoLockVersions', () => {
  const LOCK = [
    '# This file is automatically @generated by Cargo.',
    'version = 4',
    '',
    '[[package]]',
    'name = "tauri"',
    'version = "2.12.4"',
    '',
    '[[package]]',
    'name = "tauri-plugin-dialog"',
    'version = "2.8.3"',
    'source = "registry+https://github.com/rust-lang/crates.io-index"',
    '',
    '[[package]]',
    'name = "windows-core"',
    'version = "0.61.2"',
    '',
    '[[package]]',
    'name = "windows-core"',
    'version = "0.62.2"',
  ].join('\n');

  it('reads package names and versions', () => {
    expect(parseCargoLockVersions(LOCK)).toEqual({
      tauri: '2.12.4',
      'tauri-plugin-dialog': '2.8.3',
      // Duplicate crate names are legal in a lockfile; the last one wins, which
      // is harmless here because Tauri crates are unique.
      'windows-core': '0.62.2',
    });
  });
});

describe('checkTauriVersionParity', () => {
  it('accepts equal major.minor with differing patch', () => {
    expect(
      checkTauriVersionParity(
        { '@tauri-apps/plugin-dialog': '2.8.3' },
        { 'tauri-plugin-dialog': '2.8.0' },
      ),
    ).toEqual([]);
  });

  // The 2026-10-19 Release failure: npm 2.8.3 against crate 2.7.3.
  it('rejects a minor mismatch and names both sides', () => {
    const errors = checkTauriVersionParity(
      { '@tauri-apps/plugin-dialog': '2.8.3' },
      { 'tauri-plugin-dialog': '2.7.3' },
    );
    expect(errors).toHaveLength(1);
    expect(errors[0]).toContain('tauri-plugin-dialog (Rust v2.7.3)');
    expect(errors[0]).toContain('@tauri-apps/plugin-dialog (npm v2.8.3)');
  });

  it('rejects a major mismatch', () => {
    expect(
      checkTauriVersionParity({ '@tauri-apps/api': '3.0.0' }, { tauri: '2.12.4' }),
    ).toHaveLength(1);
  });

  // A pair is compared only when both halves exist, exactly like `tauri build`,
  // which skips a plugin whose crate is absent rather than failing.
  it('skips an npm package whose crate is absent', () => {
    expect(
      checkTauriVersionParity({ '@tauri-apps/plugin-opener': '2.7.2' }, {}),
    ).toEqual([]);
  });

  it('allows a Rust-only plugin (no npm half)', () => {
    expect(checkTauriVersionParity({}, { 'tauri-plugin-updater': '2.14.0' })).toEqual([]);
  });
});

describe('missingNpmPackages', () => {
  it('reports declared packages the lockfile parse did not find', () => {
    expect(
      missingNpmPackages(
        ['@tauri-apps/api', '@tauri-apps/plugin-dialog', '@tauri-apps/cli', 'vue'],
        { '@tauri-apps/api': '2.12.4' },
      ),
    ).toEqual(['@tauri-apps/plugin-dialog']);
  });

  it('ignores packages that have no crate pairing', () => {
    expect(missingNpmPackages(['@tauri-apps/cli', 'vue'], {})).toEqual([]);
  });
});

// The regression that matters: the repo's own lockfiles must agree. Without this
// the unit tests above would keep passing while the checked-in state drifts.
describe('repository lockfiles', () => {
  it('have matching Tauri npm/crate major.minor versions', () => {
    const npmVersions = parsePnpmImporterVersions(
      readFileSync(resolve(ROOT, 'pnpm-lock.yaml'), 'utf-8'),
    );
    const cargoVersions = parseCargoLockVersions(readFileSync(resolve(ROOT, 'Cargo.lock'), 'utf-8'));

    // Guard against a vacuous pass: if the lockfile layout stopped matching the
    // parser, both maps could be empty and the comparison below would trivially
    // succeed. Every declared Tauri package must have been found.
    const pkg = JSON.parse(readFileSync(resolve(ROOT, 'package.json'), 'utf-8')) as {
      dependencies?: Record<string, string>;
      devDependencies?: Record<string, string>;
    };
    const declared = [
      ...Object.keys(pkg.dependencies ?? {}),
      ...Object.keys(pkg.devDependencies ?? {}),
    ];
    expect(missingNpmPackages(declared, npmVersions)).toEqual([]);

    expect(checkTauriVersionParity(npmVersions, cargoVersions)).toEqual([]);
  });
});
